const DICTIONARIES = { en, am };

const lookup = (dictionary, key) =>
  key.split('.').reduce((node, part) => (node == null ? undefined : node[part]), dictionary);

const interpolate = (template, params) =>
  params
    ? String(template).replace(/\{(\w+)\}/g, (match, name) =>
        params[name] != null ? String(params[name]) : match
      )
    : template;

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState('en');

  const value = useMemo(() => {
    const t = (key, params) => {
      // Fall back to English, then to the key itself, so a missing
      // translation degrades to readable text instead of a blank label.
      const template = lookup(DICTIONARIES[language], key) ?? lookup(en, key) ?? key;
      return interpolate(template, params);
    };

    return {
      t,
      language,
      setLanguage,
      isAmharic: language === 'am',
      toggleLanguage: () => setLanguage((prev) => (prev === 'am' ? 'en' : 'am')),
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useI18n must be used inside a LanguageProvider');
  return context;
}
